/* Schema Factory SINTETICO per collaudare publish_factory_plan.py su SQL Server.
   Solo le colonne scritte o controllate dal Salva, con trigger che imitano gli effetti
   documentati (docs RE dati02 §4): non e' il codice ERP e non contiene dati del cliente.
   GO separa i batch: lo esegue il test, che divide il testo sulle righe "GO". */
CREATE TABLE dbo.A_COM (CONUM int NOT NULL PRIMARY KEY, COPNF int NULL,
  CODIP date NULL, COHIP time NULL, CODFP date NULL, COHFP time NULL);
CREATE TABLE dbo.A_LOT (CONUM int NOT NULL, LOCOD int NOT NULL,
  LODIP date NULL, LOHIP time NULL, LODFP date NULL, LOHFP time NULL, LASTUPDATE datetime NULL,
  PRIMARY KEY (CONUM, LOCOD));
CREATE TABLE dbo.A_LAV (IDLAV int NOT NULL PRIMARY KEY, CONUM int NOT NULL, LOCOD int NOT NULL, IDFAS int NOT NULL,
  LASTO smallint NOT NULL, FPIAN varchar(1) NULL, LADIP date NULL, LAHIP time NULL, LADFP date NULL, LAHFP time NULL,
  LADTS datetime NULL, LASCH int NULL, LASTUPDATE datetime NULL);
CREATE TABLE dbo.L_LARE (IDLARE int NOT NULL PRIMARY KEY, CONUM int NOT NULL, LOCOD int NOT NULL, IDFAS int NOT NULL,
  MACOD varchar(20) NULL, OPCOD varchar(20) NULL, RECOD varchar(20) NULL,
  RIUSE varchar(1) NULL, IDBLK int NOT NULL DEFAULT 0, RIPOC numeric(6,2) NULL, RITPU int NULL);
CREATE TABLE dbo.L_LAPN (IDINT int NOT NULL DEFAULT 0 PRIMARY KEY, CONUM int NOT NULL, LOCOD int NOT NULL, IDFAS int NOT NULL,
  IDBLK int NOT NULL, BLDIP date NOT NULL, BLHIP time NOT NULL, BLDFP date NOT NULL, BLHFP time NOT NULL,
  IDFRZ int NULL, IDPTC int NULL, RIPOC numeric(6,2) NULL);
CREATE TABLE dbo.X_PROGRESSIVO (TABELLA varchar(40) NOT NULL PRIMARY KEY, ULTIMO int NOT NULL);
GO
-- Come TRG_ON_BEFORE_INSERT_LAPN: IDINT=0 numerato da un progressivo applicativo.
CREATE TRIGGER dbo.TRG_TEST_INSERT_LAPN ON dbo.L_LAPN INSTEAD OF INSERT AS
BEGIN
  SET NOCOUNT ON;
  DECLARE @n int = (SELECT COUNT(*) FROM inserted WHERE ISNULL(IDINT, 0) = 0), @last int;
  UPDATE dbo.X_PROGRESSIVO SET @last = ULTIMO, ULTIMO = ULTIMO + @n WHERE TABELLA = 'dbo.L_LAPN';
  INSERT INTO dbo.L_LAPN (IDINT, CONUM, LOCOD, IDFAS, IDBLK, BLDIP, BLHIP, BLDFP, BLHFP, IDFRZ, IDPTC, RIPOC)
  SELECT CASE WHEN ISNULL(IDINT, 0) = 0 THEN @last + ROW_NUMBER() OVER (PARTITION BY CASE WHEN ISNULL(IDINT, 0) = 0 THEN 0 ELSE 1 END ORDER BY CONUM, LOCOD, IDFAS, IDBLK, BLDIP, BLHIP) ELSE IDINT END,
         CONUM, LOCOD, IDFAS, IDBLK, BLDIP, BLHIP, BLDFP, BLHFP, IDFRZ, IDPTC, RIPOC FROM inserted;
END;
GO
-- Come TRG_ON_DELETE_LAPN: cancellare i blocchi azzera IDBLK delle risorse collegate.
CREATE TRIGGER dbo.TRG_TEST_DELETE_LAPN ON dbo.L_LAPN AFTER DELETE AS
BEGIN
  SET NOCOUNT ON;
  UPDATE r SET IDBLK = 0 FROM dbo.L_LARE r JOIN deleted d
    ON d.CONUM = r.CONUM AND d.LOCOD = r.LOCOD AND d.IDFAS = r.IDFAS AND d.IDBLK = r.IDBLK;
END;
GO
-- Come TRG_ON_UPDATE_LAV: ogni UPDATE della fase rinnova LASTUPDATE.
CREATE TRIGGER dbo.TRG_TEST_UPDATE_LAV ON dbo.A_LAV AFTER UPDATE AS
BEGIN
  SET NOCOUNT ON;
  IF NOT UPDATE(LASTUPDATE)
    UPDATE l SET LASTUPDATE = DATEADD(second, 1, ISNULL(l.LASTUPDATE, GETDATE())) FROM dbo.A_LAV l JOIN inserted i ON i.IDLAV = l.IDLAV;
END;
GO
